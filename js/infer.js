  var CAPS = { use: 3, trouble: 5, style: 2, mood: 2, color: 2, scene: 3, frame: 2, people: 3, option: 2, change: 4, keep: 3 };

  function norm(s) {
    var t = String(s == null ? '' : s);
    try { t = t.normalize('NFKC'); } catch (e) { /* 古い環境ではそのまま */ }
    return t;
  }


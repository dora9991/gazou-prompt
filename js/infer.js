  function split(text, mode) {
    text = String(text == null ? '' : text).trim();
    if (!text || mode === 'edit') return { wish: text, trouble: '' };
    var r = remember('split', text, function () { return splitNow(text); });
    return { wish: r.wish, trouble: r.trouble };
  }
  function splitNow(text) {
    var parts = (text.match(/[^。．\n!！?？]+[。．!！?？]?/g) || []).map(function (s) { return s.trim(); }).filter(Boolean);
    if (parts.length < 2) return { wish: text, trouble: '' };
    var end = function (s) { return /[。．!！?？]$/.test(s) ? s : s + '。'; };
    var wish = [], trouble = [];
    parts.forEach(function (p) { (isTrouble(p) ? trouble : wish).push(end(p)); });
    if (!wish.length && trouble.length && hasContent(text)) wish = trouble.slice();
    return { wish: wish.join(''), trouble: trouble.join('') };
  }


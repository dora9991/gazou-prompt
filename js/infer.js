  var COMPILED = RULES.filter(function (r) { return TAGS.byId(r[0]); }).map(function (r) {
    var t = TAGS.byId(r[0]), cat = TAGS.CAT[t.cat];
    return { id: r[0], re: r[1], cat: t.cat, multi: cat.multi, modes: cat.modes };
  });

  // 文章の中で、当てはまるタグ（出てきた位置つき）を全部返す。only：この種類だけ調べる（省略で全部）
  function match(text, mode, only) {
    var hits = [];
    for (var i = 0; i < COMPILED.length; i++) {
      var r = COMPILED[i];
      if (only && r.cat !== only) continue;
      if (r.modes.indexOf(mode) < 0) continue;
      var m = r.re.exec(text);
      if (m) hits.push({ id: r.id, cat: r.cat, multi: r.multi, pos: m.index });
    }
    return hits;
  }

